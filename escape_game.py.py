def draw_floor():
    n = 26
    glBegin(GL_QUADS)
    for r in range(n):
        for c in range(n):
            if (r + c) % 2 == 0:
                glColor3f(1.0, 1.0, 1.0)
            else:
                glColor3f(174 / 255, 193 / 255, 207 / 255)
            x1, y1 = r * CELL, c * CELL
            x2, y2 = x1 + CELL, y1 + CELL
            glVertex3f(x1, y1, 0)
            glVertex3f(x2, y1, 0)
            glVertex3f(x2, y2, 0)
            glVertex3f(x1, y2, 0)
    glEnd()


def draw_walls():
    # Tiled walls (checker pattern, like the original)
    tiles_h = int(WALL_H / CELL)

    def wall(fixed_axis, fixed_val):
        glBegin(GL_QUADS)
        for i in range(26):
            for j in range(tiles_h):
                if (i + j) % 2 == 0:
                    glColor3f(0.8, 0.8, 0.8)
                else:
                    glColor3f(0.7, 0.7, 0.7)
                a1, a2 = i * CELL, (i + 1) * CELL
                z1, z2 = j * CELL, (j + 1) * CELL
                if fixed_axis == "y":
                    glVertex3f(a1, fixed_val, z1)
                    glVertex3f(a2, fixed_val, z1)
                    glVertex3f(a2, fixed_val, z2)
                    glVertex3f(a1, fixed_val, z2)
                else:
                    glVertex3f(fixed_val, a1, z1)
                    glVertex3f(fixed_val, a2, z1)
                    glVertex3f(fixed_val, a2, z2)
                    glVertex3f(fixed_val, a1, z2)
        glEnd()

    wall("y", 0)
    wall("y", ROOM)
    wall("x", 0)
    wall("x", ROOM)


def draw_door():
    w = CELL * 4
    h = WALL_H * 0.8
    cx, cy = DOOR_POS
    # frame
    glColor3f(0.1, 0.1, 0.1)
    glBegin(GL_QUADS)
    glVertex3f(cx - w * 0.55, cy + 0.5, 0)
    glVertex3f(cx + w * 0.55, cy + 0.5, 0)
    glVertex3f(cx + w * 0.55, cy + 0.5, h * 1.05)
    glVertex3f(cx - w * 0.55, cy + 0.5, h * 1.05)
    glEnd()
    # surface: dark when closed, bright when open
    if S.door_open:
        glColor3f(1.0, 1.0, 0.9)
    else:
        glColor3f(0.15, 0.15, 0.17)
    glBegin(GL_QUADS)
    glVertex3f(cx - w / 2, cy + 1.5, 0)
    glVertex3f(cx + w / 2, cy + 1.5, 0)
    glVertex3f(cx + w / 2, cy + 1.5, h)
    glVertex3f(cx - w / 2, cy + 1.5, h)
    glEnd()
    if not S.door_open:
        # panels
        glColor3f(0.12, 0.12, 0.14)
        for k in range(3):
            z1 = k * h / 3 + 3
            z2 = (k + 1) * h / 3 - 3
            glBegin(GL_QUADS)
            glVertex3f(cx - w / 2 + 3, cy + 2.5, z1)
            glVertex3f(cx + w / 2 - 3, cy + 2.5, z1)
            glVertex3f(cx + w / 2 - 3, cy + 2.5, z2)
            glVertex3f(cx - w / 2 + 3, cy + 2.5, z2)
            glEnd()



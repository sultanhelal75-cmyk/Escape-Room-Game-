def nearest_hint():
    px, py = S.pos
    if S.pending_cut and math.hypot(px - SAW_POS[0], py - SAW_POS[1]) < 60:
        return "Press E to grab the SAW"
    if S.locks < 4 and math.hypot(px - BOOK_POS[0], py - BOOK_POS[1]) < 90:
        return "Press E to open the book (quiz)"
    if S.locks >= 4 and not S.has_key and math.hypot(px - CHEST_POS[0], py - CHEST_POS[1]) < 110:
        return "Press E to take the golden key"
    if math.hypot(px - DOOR_POS[0], py - DOOR_POS[1]) < 90:
        return "Press E to open the door" if S.has_key else "The door is locked - find the key"
    return ""



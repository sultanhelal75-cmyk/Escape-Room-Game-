    fy = math.sin(math.radians(S.angle))
    ex = min(max(S.pos[0] - fx * 140, 8), ROOM - 8)   # keep camera inside the room
    ey = min(max(S.pos[1] - fy * 140, 8), ROOM - 8)
    gluLookAt(ex, ey, 110,
              S.pos[0] + fx * 60, S.pos[1] + fy * 60, 40,
              0, 0, 1)



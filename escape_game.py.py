def cube(cx, cy, cz, sx, sy, sz, color):
    glColor3f(*color)
    glPushMatrix()
    glTranslatef(cx, cy, cz)
    glScalef(sx, sy, sz)
    glutSolidCube(1.0)
    glPopMatrix()


def draw_text(x, y, message, color=(1, 1, 1), font=None):
    if font is None:
        # NOTE: GLUT_BITMAP_HELVETICA_20 does not exist. Valid sizes: 10, 12, 18.
        font = GLUT_BITMAP_HELVETICA_18
    glColor3f(*color)
    glRasterPos2f(x, y)
    for ch in message:
        glutBitmapCharacter(font, ord(ch))


def begin_2d():
    glDisable(GL_DEPTH_TEST)
    glMatrixMode(GL_PROJECTION)
    glPushMatrix()
    glLoadIdentity()
    gluOrtho2D(0, 1000, 0, 800)
    glMatrixMode(GL_MODELVIEW)
    glPushMatrix()
    glLoadIdentity()


def end_2d():
    glMatrixMode(GL_PROJECTION)
    glPopMatrix()
    glMatrixMode(GL_MODELVIEW)
    glPopMatrix()
    glEnable(GL_DEPTH_TEST)


def rect_2d(x1, y1, x2, y2, color, alpha=1.0):
    glEnable(GL_BLEND)
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA)
    glColor4f(color[0], color[1], color[2], alpha)
    glBegin(GL_QUADS)
    glVertex2f(x1, y1)
    glVertex2f(x2, y1)
    glVertex2f(x2, y2)
    glVertex2f(x1, y2)
    glEnd()
    glDisable(GL_BLEND)



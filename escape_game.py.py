def reshape(w, h):
    global win_w, win_h
    win_w, win_h = max(w, 1), max(h, 1)


def key_down(key, x, y):
    global S
    k = key.decode("latin-1").lower() if isinstance(key, bytes) else str(key).lower()

    if k == "\x1b":
        sys.exit(0)
    if k == "r":
        S = State()
        S.mode = "play"
        keys.clear()
        return
    if S.mode == "menu":
        if k == " ":
            S.mode = "play"
            S.say("Find the book (north wall) and press E.", 6)
        return
    if S.mode == "quiz":
        mapping = {"1": 0, "2": 1, "3": 2, "4": 3, "a": 0, "b": 1, "c": 2, "d": 3}
        if k in mapping:
            answer(mapping[k])
        return
    if S.mode == "play":
        if k == "e":
            interact()
        elif k == "v":
            S.top_view = not S.top_view
        elif k in ("w", "a", "s", "d"):
            keys.add(k)


def key_up(key, x, y):
    k = key.decode("latin-1").lower() if isinstance(key, bytes) else str(key).lower()
    keys.discard(k)


def tick(_):
    update()
    glutPostRedisplay()
    glutTimerFunc(16, tick, 0)



def blocked(x, y):
    """True if (x, y) is inside the chest or book pedestal (with player radius)."""
    r = 14
    cw, cd, _ = CHEST_SIZE
    if abs(x - CHEST_POS[0]) < cw / 2 + r and abs(y - CHEST_POS[1]) < cd / 2 + r:
        return True
    if abs(x - BOOK_POS[0]) < 25 + r and abs(y - BOOK_POS[1]) < 20 + r:
        return True
    return False


def start_quiz():
    S.mode = "quiz"
    S.q_start = time.time()


def answer(choice):
    qd = QUESTIONS[S.q]
    if choice == qd["correct"]:
        S.locks += 1
        if S.q < len(QUESTIONS) - 1:
            S.q += 1
            S.q_start = time.time()       # next question right away
            S.say("Correct! A lock opened.")
        else:
            S.mode = "play"
            S.say("All locks open! Take the key from the chest.", 6)
    else:
        S.mode = "play"
        S.pending_cut = True
        S.villain_active = True
        S.say("WRONG! Collect the saw... and watch out for the villain!", 6)


def cut_limb():
    alive = [k for k, v in S.limbs.items() if v]
    if alive:
        S.limbs[random.choice(alive)] = False
    S.pending_cut = False
    if S.limb_count() == 0:
        S.mode = "lost"
        S.end_text = "You lost all your limbs."
    else:
        S.say("You lost a limb! You move slower now.", 5)


def interact():
    px, py = S.pos
    if S.pending_cut and math.hypot(px - SAW_POS[0], py - SAW_POS[1]) < 60:
        cut_limb()
        return
    if S.pending_cut and math.hypot(px - BOOK_POS[0], py - BOOK_POS[1]) < 90:
        S.say("First pay the price: grab the saw!")
        return
    if S.locks < 4 and math.hypot(px - BOOK_POS[0], py - BOOK_POS[1]) < 90:
        start_quiz()
        return
    if S.locks >= 4 and not S.has_key and math.hypot(px - CHEST_POS[0], py - CHEST_POS[1]) < 110:
        S.has_key = True
        S.say("You got the golden key! Run to the door!", 5)
        return
    if math.hypot(px - DOOR_POS[0], py - DOOR_POS[1]) < 90:
        if S.has_key:
            S.door_open = True
            S.say("The door is open - walk through it!", 5)
        else:
            S.say("Locked. You need the golden key.")


def update():
    now = time.time()
    if S.mode == "quiz":
        if now - S.q_start > TIME_PER_Q:
            S.say("Time's up!")
            answer(-1)
        return
    if S.mode != "play":
        return

    # turning
    if "a" in keys:
        S.angle += 3
    if "d" in keys:
        S.angle -= 3
    S.angle %= 360

    # moving (axis-separated so you slide along obstacles)
    step = 0.0
    if "w" in keys:
        step += S.speed()
    if "s" in keys:
        step -= S.speed() * 0.7
    if step:
        nx = S.pos[0] + math.cos(math.radians(S.angle)) * step
        ny = S.pos[1] + math.sin(math.radians(S.angle)) * step
        if S.door_open and abs(nx - DOOR_POS[0]) < CELL * 2 - 10:
            min_y = -30            # allowed to walk out through the open door
        else:
            min_y = 18
        nx = min(max(nx, 18), ROOM - 18)
        ny = min(max(ny, min_y), ROOM - 18)
        if not blocked(nx, S.pos[1]):
            S.pos[0] = nx
        if not blocked(S.pos[0], ny):
            S.pos[1] = ny

    # escape!
    if S.door_open and S.pos[1] < 8:
        S.mode = "won"
        S.end_text = "You solved the quiz, took the key and got out."
        return

    # villain chase
    if S.villain_active:
        dx = S.pos[0] - S.villain[0]
        dy = S.pos[1] - S.villain[1]
        dist = math.hypot(dx, dy)
        S.villain_angle = math.degrees(math.atan2(dy, dx))
        if dist > 28:
            S.villain[0] += dx / dist * 1.0
            S.villain[1] += dy / dist * 1.0
        else:
            S.mode = "lost"
            S.end_text = "The villain caught you."



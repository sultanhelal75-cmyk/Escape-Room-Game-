"""
Escape Room Game (PyOpenGL + GLUT) - fixed, runnable version.

Goal: answer the quiz in the book to unlock the 4 locks on the chest,
take the golden key, then open the door and escape.
A wrong answer (or running out of time) means you must grab the SAW and
lose a limb, and the villain starts chasing you.

Controls
    SPACE        start game
    W / S        move forward / backward
    A / D        turn left / right
    E            interact (book, chest key, door, saw)
    1-4 or A-D   answer quiz questions
    V            toggle top view
    R            restart
    ESC          quit
"""


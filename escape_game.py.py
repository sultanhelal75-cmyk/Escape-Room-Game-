# --------------------------------------------------------------------------
# Game state
# --------------------------------------------------------------------------
class State:
    def __init__(self):
        self.mode = "menu"            # menu, play, quiz, won, lost
        self.pos = [300.0, 120.0]
        self.angle = 90.0             # degrees, 90 = facing +Y
        self.limbs = {"la": True, "ra": True, "ll": True, "rl": True}
        self.pending_cut = False      # must collect the saw
        self.locks = 0
        self.q = 0
        self.q_start = 0.0
        self.has_key = False
        self.door_open = False
        self.villain = [80.0, 520.0]
        self.villain_angle = 0.0
        self.villain_active = False
        self.msg = ""
        self.msg_until = 0.0
        self.top_view = False
        self.end_text = ""

    def say(self, text, seconds=4):
        self.msg = text
        self.msg_until = time.time() + seconds

    def limb_count(self):
        return sum(1 for v in self.limbs.values() if v)

    def speed(self):
        return 1.2 + 0.7 * self.limb_count()


S = State()
keys = set()
quad = None
